import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { build } from 'esbuild'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const manifest = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/client/index.tsx'],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['es2022'],
  jsx: 'automatic',
  charset: 'utf8',
  external: ['react', 'react/jsx-runtime'],
  legalComments: 'none',
})

const body = result.outputFiles[0]?.text
if (body === undefined) throw new Error('esbuild produced no client bundle')
const bundle = `/* ${manifest.name} ${manifest.version} — generated by scripts/build-client.mjs */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(manifest.name)},
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
    (function (module, exports, require) {
${indent(body, 6)}
    }).call(module.exports, module, module.exports, require);
    return module.exports;
  },
});
`
await writeFile(join(root, 'client.js'), bundle)
console.log(`built client.js (${Buffer.byteLength(bundle)} bytes)`)

function indent(value, spaces) {
  const prefix = ' '.repeat(spaces)
  return value.split('\n').map(line => `${prefix}${line}`).join('\n')
}
